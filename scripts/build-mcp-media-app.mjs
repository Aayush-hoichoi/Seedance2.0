import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const entry = resolve(root, 'lib/mcp/ui/mediaApp.js');
const output = resolve(root, 'lib/mcp/ui/mediaAppBundle.mjs');

const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    write: false,
});
// Prevent a dependency string from accidentally closing the HTML script tag.
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/build-mcp-media-app.mjs.\nexport const MEDIA_APP_SCRIPT = ${JSON.stringify(script)};\n`);
